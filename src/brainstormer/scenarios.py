
"""
Structured API testing scenario models.

Scenarios are generated by the local LLM, validated using Pydantic,
and grounded against the actual OpenAPI specification before use.
"""

from __future__ import annotations

from enum import Enum

from pydantic import BaseModel, Field, ConfigDict


class ScenarioType(str, Enum):
    VALID = "valid"
    BOUNDARY = "boundary"
    INVALID = "invalid"


class ScenarioStep(BaseModel):
    model_config = ConfigDict(extra="forbid")

    operation_id: str = Field(
        ...,
        description="Must exactly match an operationId from the OpenAPI specification."
    )

    http_method: str = Field(
        ...,
        description="HTTP method from the OpenAPI operation, such as GET, POST, PUT, PATCH or DELETE."
    )

    parameters: dict[str, str | int | float | bool | None] = Field(
        default_factory=dict,
        description="Input parameters for this API operation."
    )

    hint: str = Field(
        default="",
        description="Short explanation of the input values or testing condition."
    )


class Scenario(BaseModel):
    model_config = ConfigDict(extra="forbid")

    sequence: list[ScenarioStep] = Field(
        ...,
        min_length=1,
        max_length=2,
        description="One or two ordered API operations."
    )

    scenario_type: ScenarioType = Field(
        ...,
        description="Whether this scenario tests valid, boundary or invalid inputs."
    )

    hypothesis: str = Field(
        ...,
        min_length=1,
        description="The possible API behaviour or defect being investigated."
    )

    purpose: str = Field(
        ...,
        min_length=1,
        description="The specific testing objective of this scenario."
    )

    tag: str = Field(
        ...,
        description=(
            "One of: state-inconsistency, auth-boundary, "
            "ordering-effect, race-condition, other."
        )
    )


class ScenarioBatch(BaseModel):
    model_config = ConfigDict(extra="forbid")

    scenarios: list[Scenario] = Field(
        default_factory=list,
        description="Generated API testing scenarios."
    )


# JSON schema supplied to Ollama structured-output generation.
SCENARIO_BATCH_JSON_SCHEMA = ScenarioBatch.model_json_schema()
